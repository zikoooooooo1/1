export type Locale = 'en' | 'ar';
const Context = createContext<{
  locale: Locale;
  setLocale: (s: Locale) => void;
  t: (s: string) => string;
  formatDate: (s: string, time?: boolean) => string;
  number: (n: number) => string;
  timezone: string;
}>({} as any);
export function LocaleProvider({
  children,
  timezone = 'UTC',
}: {
  children: React.ReactNode;
  timezone?: string;
}) {
  const [locale, set] = useState<Locale>(() => {
    try {
      const saved = localStorage.getItem('claso-locale');
      return saved === 'ar' || saved === 'en'
        ? saved
        : navigator.language.startsWith('ar')
          ? 'ar'
          : 'en';
    } catch {
      return 'en';
    }
  });
  React.useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
  }, [locale]);
  const setLocale = (s: Locale) => {
    set(s);
    try {
      localStorage.setItem('claso-locale', s);
    } catch {
      /* preference remains in memory */
    }
  };
  const t = (s: string) => messages[s]?.[locale === 'ar' ? 1 : 0] || s;
  const formatDate = (s: string, time = false) => {
    if (!s) return '—';
    const d = new Date(s);
    return Number.isNaN(d.getTime())
      ? s
      : new Intl.DateTimeFormat(locale, {
          dateStyle: 'medium',
          ...(time
            ? { timeStyle: 'short', timeZone: timezone }
            : { timeZone: s.length === 10 ? 'UTC' : timezone }),
        }).format(d);
  };
  return (
    <Context.Provider
      value={{
        locale,
        setLocale,
        t,
        formatDate,
        number: (n) => new Intl.NumberFormat(locale).format(n),
        timezone,
      }}
    >
      {children}
    </Context.Provider>
  );
}
export const useLocale = () => useContext(Context);
